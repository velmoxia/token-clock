"""Token Clock: summary statistics from token_clock_moves.csv. Usage: python stats.py <moves.csv> <out.md>"""
import sys, pandas as pd, numpy as np
from scipy.stats import spearmanr
df = pd.read_csv(sys.argv[1]); out = []
CLS = ["best", "good", "inaccuracy", "mistake", "blunder"]
P = lambda s: out.append(s)

def block(d, title):
    P(f"\n## {title}\n")
    P("| Player | Moves | ACPL | Median CPL | Engine first choice | Best class | Mistakes + blunders | Median output tokens | Mean output tokens |")
    P("|---|---|---|---|---|---|---|---|---|")
    for p, x in d.groupby("player"):
        eff = "/".join(sorted(x.effort.unique()))
        P(f"| {x.model.iloc[0]} ({eff}) | {len(x)} | {x.cpl.mean():.1f} | {x.cpl.median():.0f} | {100*x.played_engine_best.mean():.1f}% | "
          f"{100*(x.cls=='best').mean():.1f}% | {100*x.cls.isin(['mistake','blunder']).mean():.1f}% | {x.output_tokens.median():.0f} | {x.output_tokens.mean():.0f} |")

s = df[df.set == "series"]
P("# Token Clock: results\n\nGenerated by `analysis/stats.py`. CPL = centipawn loss, capped at 1000. ACPL = average CPL.")
block(s, "Series (11 games, both models on reasoning effort high)")
P("\n## Series: median output tokens by move quality\n\n| Class | " + " | ".join(f"{m} (n)" for m in sorted(s.model.unique())) + " |\n|---|" + "---|" * s.model.nunique())
for c in CLS:
    P(f"| {c} | " + " | ".join(f"{x[x.cls==c].output_tokens.median():.0f} ({(x.cls==c).sum()})" if (x.cls==c).any() else "n/a (0)" for _, x in sorted(s.groupby("model"))) + " |")
P("\n## Series: does more output go with worse moves? (Spearman rank correlation, per move)\n\n| Model | tokens vs CPL | tokens vs candidate moves within 40 cp | tokens vs gap between 1st and 2nd engine move | tokens vs ply |\n|---|---|---|---|---|")
rng = np.random.default_rng(1)
for m, x in sorted(s.groupby("model")):
    x = x.copy(); x["gap"] = x.eval_before - pd.to_numeric(x.eval_second, errors="coerce")
    def r(col):
        y = x.dropna(subset=[col]); rho = spearmanr(y.output_tokens, y[col])[0]
        games = y.game.unique(); bs = []
        for _ in range(2000):  # bootstrap over games, not moves: moves inside a game are not independent
            z = pd.concat([y[y.game == g] for g in rng.choice(games, len(games))]); bs.append(spearmanr(z.output_tokens, z[col])[0])
        lo, hi = np.nanpercentile(bs, [2.5, 97.5]); return f"{rho:+.2f} [{lo:+.2f}, {hi:+.2f}]"
    P(f"| {m} | {r('cpl')} | {r('candidates_within_40cp')} | {r('gap')} | {r('ply')} |")
P("\nBrackets: 95% interval from 2000 bootstrap resamples of whole games.")
P("\n## Series: robustness of tokens vs CPL\n\n| Model | Subset | Moves | Spearman |\n|---|---|---|---|")
for m, x in sorted(s.groupby("model")):
    for name, y in [("all moves", x), ("without the opening (ply > 20)", x[x.phase != "opening"]),
                    ("without the opening, position within +/-200 cp", x[(x.phase != "opening") & (x.eval_before.abs() <= 200)])]:
        P(f"| {m} | {name} | {len(y)} | {spearmanr(y.output_tokens, y.cpl)[0]:+.2f} |")
P("\n## Series: by phase\n\n| Model | Phase | Moves | ACPL | Median output tokens |\n|---|---|---|---|---|")
for (m, ph), x in s.groupby(["model", "phase"]):
    P(f"| {m} | {ph} | {len(x)} | {x.cpl.mean():.1f} | {x.output_tokens.median():.0f} |")
P("\n## Per game\n\n| Game | Set | Model | Effort | Colour | Moves | ACPL | Mistakes + blunders | Total output tokens |\n|---|---|---|---|---|---|---|---|---|")
for (g, p), x in df.groupby(["game", "player"], sort=False):
    P(f"| {g} | {x.set.iloc[0]} | {x.model.iloc[0]} | {x.effort.iloc[0]} | {'white' if x.ply.iloc[0]==1 else 'black'} | {len(x)} | {x.cpl.mean():.1f} | {x.cls.isin(['mistake','blunder']).sum()} | {x.output_tokens.sum()} |")
for g in ["P1", "P2"]:
    block(df[df.game == g], f"Pilot {g} (single game, shown separately)")
open(sys.argv[2], "w").write("\n".join(out) + "\n"); print("\n".join(out))
